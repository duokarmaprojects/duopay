import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

export function getBuildId() {
  if (process.env.VERCEL_GIT_COMMIT_SHA) {
    return process.env.VERCEL_GIT_COMMIT_SHA.slice(0, 7);
  }
  if (process.env.NEXT_PUBLIC_BUILD_ID) {
    return process.env.NEXT_PUBLIC_BUILD_ID.slice(0, 7);
  }
  try {
    const gitHash = execSync('git rev-parse --short HEAD', { cwd: rootDir, encoding: 'utf8' }).trim();
    if (gitHash && /^[0-9a-fA-F]+$/.test(gitHash)) {
      return gitHash;
    }
  } catch (err) {
    // Git not available or not in a git repo
  }
  return 'build-' + Date.now().toString(36);
}

export function generatePwaVersion() {
  const buildId = getBuildId();
  const version = '2026.10.' + buildId;
  const staticCache = 'duopay-static-' + buildId;
  const runtimeCache = 'duopay-runtime-' + buildId;

  console.log(`[PWA Version Generator] Generating build artifacts for version: ${version} (${buildId})`);

  // 1. Generate src/lib/pwa/version.ts
  const versionTsDir = path.join(rootDir, 'src', 'lib', 'pwa');
  if (!fs.existsSync(versionTsDir)) {
    fs.mkdirSync(versionTsDir, { recursive: true });
  }

  const versionTsContent = `// Automatically generated by scripts/generate-pwa-version.mjs
export const APP_VERSION = '${version}';
export const BUILD_ID = '${buildId}';
export const CACHE_STATIC_NAME = '${staticCache}';
export const CACHE_RUNTIME_NAME = '${runtimeCache}';
`;
  fs.writeFileSync(path.join(versionTsDir, 'version.ts'), versionTsContent, 'utf8');

  // 2. Generate public/sw.js from src/pwa/sw-template.js
  const templatePath = path.join(rootDir, 'src', 'pwa', 'sw-template.js');
  if (fs.existsSync(templatePath)) {
    let swContent = fs.readFileSync(templatePath, 'utf8');
    swContent = swContent
      .replace(/__SW_BUILD_ID__/g, buildId)
      .replace(/__SW_VERSION__/g, version);

    const publicSwPath = path.join(rootDir, 'public', 'sw.js');
    fs.writeFileSync(publicSwPath, swContent, 'utf8');
    console.log(`[PWA Version Generator] Generated public/sw.js with build ID ${buildId}`);
  } else {
    console.warn(`[PWA Version Generator] Template not found at ${templatePath}`);
  }

  return { buildId, version, staticCache, runtimeCache };
}

// Run immediately if executed directly
if (process.argv[1] === __filename) {
  generatePwaVersion();
}
